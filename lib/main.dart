import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:map/auths/authwrapper.dart';
import 'package:mapbox_maps_flutter/mapbox_maps_flutter.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // Auto-generated by FlutterFire CLI

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  if (kDebugMode) {
    debugPrint('Loading .env asset (web: $kIsWeb)');
  }
  try {
    await dotenv.load(fileName: ".env");
    if (kDebugMode) {
      debugPrint(
        '.env loaded; MAPBOX_ACCESS_TOKEN: '
        '${dotenv.maybeGet('MAPBOX_ACCESS_TOKEN')?.isNotEmpty ?? false}, '
        'SUPABASE_URL: ${dotenv.maybeGet('SUPABASE_URL')?.isNotEmpty ?? false}, '
        'SUPABASE_ANON_KEY: '
        '${dotenv.maybeGet('SUPABASE_ANON_KEY')?.isNotEmpty ?? false}',
      );
    }
  } on Object catch (error, stackTrace) {
    if (kDebugMode) {
      debugPrint('Failed to load .env asset: $error');
      debugPrintStack(stackTrace: stackTrace);
    }
    rethrow;
  }
  final accessToken = dotenv.get('MAPBOX_ACCESS_TOKEN');
  MapboxOptions.setAccessToken(accessToken);
  await Supabase.initialize(
    url: dotenv.get('SUPABASE_URL'),
    anonKey: dotenv.get('SUPABASE_ANON_KEY'),
  );
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  // This widget is the root of your application.
  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'Map App',
      theme: ThemeData(primarySwatch: Colors.blue),
      home: AuthWrapper(),
    );
  }
}
